export function generateHTML(project) {
  const components = project.components || [];
  const css = generateCSS(project);
  const title = project.title || 'Website';
  const bodyContent = components.map(c =>
    `    <div class="pandora-component">${renderComponentToHTML(c)}</div>`
  ).join('\n');

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <meta name="description" content="Built with Pandora Web Builder">
  <title>${escapeAttr(title)}</title>
  <style>
${css}
  </style>
</head>
<body>
  <div class="pandora-container">
${bodyContent}
  </div>
</body>
</html>`;
}

export function generateCSSOnly(project) {
  return generateCSS(project);
}

export function downloadHTML(project) {
  const html = generateHTML(project);
  const blob = new Blob([html], { type: 'text/html;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${project.title || 'website'}.html`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function downloadCSS(project) {
  const css = generateCSSOnly(project);
  const blob = new Blob([css], { type: 'text/css;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${project.title || 'styles'}.css`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export function previewHTML(project) {
  const html = generateHTML(project);
  const w = window.open('', '_blank', 'width=1200,height=800,scrollbars=yes');
  if (w) {
    w.document.write(html);
    w.document.close();
  }
}

export function getExportCode(project) {
  return {
    html: generateHTML(project),
    css: generateCSSOnly(project),
  };
}
