function escapeAttr(val) {
  return String(val).replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function renderComponentToHTML(comp) {
  const p = comp.props || {};
  switch (comp.type) {
    case 'button':
      return `<button class="pandora-btn pandora-btn--${p.size || 'md'}" style="background:${p.bgColor || '#0066cc'};color:${p.textColor || '#fff'};border-radius:${p.borderRadius || '6px'}">${escapeAttr(p.text || 'Click me')}</button>`;
    case 'card':
      return `<div class="pandora-card" style="background:${p.bgColor || '#fff'}">${p.image ? `<img src="${escapeAttr(p.image)}" alt="${escapeAttr(p.title || '')}" class="pandora-card__image"/>` : ''}<div class="pandora-card__body"><h3 class="pandora-card__title">${escapeAttr(p.title || 'Card Title')}</h3><p class="pandora-card__desc">${escapeAttr(p.description || 'Card description')}</p></div></div>`;
    case 'section':
      return `<section class="pandora-section" style="background:${p.bgColor || '#f5f5f5'};padding:${p.padding || '40px'};text-align:${p.textAlign || 'left'}">${p.title ? `<h2 class="pandora-section__title">${escapeAttr(p.title)}</h2>` : ''}<div class="pandora-section__content" style="min-height:100px"></div></section>`;
    case 'input':
      return `<div class="pandora-input-group">${p.label ? `<label class="pandora-input-group__label">${escapeAttr(p.label)}</label>` : ''}<input type="${escapeAttr(p.type || 'text')}" placeholder="${escapeAttr(p.placeholder || 'Enter text...')}" class="pandora-input" style="width:${p.width || '100%'}"/></div>`;
    case 'heading':
      return `<${p.level || 'h1'} class="pandora-heading pandora-heading--${p.level || 'h1'}" style="color:${p.color || '#333'};text-align:${p.textAlign || 'left'}">${escapeAttr(p.text || 'Your Heading')}</${p.level || 'h1'}>`;
    case 'text':
      return `<p class="pandora-text" style="color:${p.color || '#555'};font-size:${p.fontSize || '16px'};text-align:${p.textAlign || 'left'}">${escapeAttr(p.content || 'Your text content here...')}</p>`;
    case 'image':
      return `<img src="${escapeAttr(p.src || 'https://via.placeholder.com/400x300')}" alt="${escapeAttr(p.alt || 'Image')}" class="pandora-image" style="width:${p.width || '100%'};height:${p.height || 'auto'};border-radius:${p.borderRadius || '0px'}"/>`;
    case 'spacer':
      return `<div class="pandora-spacer" style="height:${p.height || '40px'}"></div>`;
    case 'divider':
      return `<hr class="pandora-divider" style="border-top:${p.thickness || '1px'} solid ${p.color || '#ddd'};margin:${p.margin || '20px 0'}"/>`;
    case 'video':
      return `<div class="pandora-video-wrapper" style="width:${p.width || '100%'};max-width:100%"><iframe src="${escapeAttr(p.src)}" height="${p.height || '315px'}" class="pandora-video" allowfullscreen title="video"></iframe></div>`;
    case 'list':
      const items = Array.isArray(p.items) ? p.items : ['Item 1', 'Item 2', 'Item 3'];
      const tag = p.style === 'number' ? 'ol' : 'ul';
      return `<${tag} class="pandora-list" style="color:${p.color || '#555'}">${items.map(i => `<li>${escapeAttr(i)}</li>`).join('')}</${tag}>`;
    case 'link':
      return `<a href="${escapeAttr(p.url || '#')}" target="${escapeAttr(p.target || '_blank')}" class="pandora-link" style="color:${p.color || '#0066cc'}">${escapeAttr(p.text || 'Click here')}</a>`;
    default:
      return `<div class="pandora-unknown" style="padding:10px;border:1px dashed #ddd">${comp.type}</div>`;
  }
}

